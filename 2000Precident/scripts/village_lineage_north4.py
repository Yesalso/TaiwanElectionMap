def build_split_index(normalize=lambda s: s, enabled=True):
    """(鄉鎮市區, 子里) → [母里, ...]；同一子里可能有多個母里（合併案）。

    normalize 由呼叫端注入（與底圖／得票資料同一套正規化），使沿革表用字
    （如 峯/峰、獇/羌、舘/館）與實際查表鍵收斂到一致。
    """
    idx = {}
    if not enabled:
        return idx
    for town, pairs in VILLAGE_SPLITS.items():
        t = normalize(town)
        for parent, child in pairs:
            idx.setdefault((t, normalize(child)), []).append(normalize(parent))
    return idx


def resolve_unit_name(town, vill, exists_keys, split_index, year=None, split_years=None):
    """回傳該里在選舉當年（2000）所對應的行政單元名稱。

    自身名稱於當年資料中存在 → 用自身；
    不存在且為已知「由母里分出」之里 → 往上追溯母里（可連續追溯）；
    若已知該里成立年 <= 選舉年（表示當年已設里，只是資料缺列）→ 不併入，維持自身；
    母里亦查無資料 → 回傳該里自身（視為無資料）。
    """
    if (town, vill) in exists_keys:
        return vill
    parents = split_index.get((town, vill))
    if not parents:
        return vill
    cy = (split_years or {}).get((town, vill))
    if year is not None and cy is not None and year >= cy:
        return vill
    for parent in parents:
        if (town, parent) in exists_keys:
            return parent
    cur, seen = parents[0], {vill}
    while cur and (town, cur) not in exists_keys and cur not in seen:
        seen.add(cur)
        nxt = split_index.get((town, cur))
        if not nxt:
            break
        cur = nxt[0]
    return cur


# ============================================================================
# 四縣市沿革表查詢（(縣市, 鄉鎮市區) 為鍵，避免同名區撞鍵）
# ----------------------------------------------------------------------------
# 呼叫端傳入的 town 已由 nat.strip_town_suffix 去尾綴（七堵區→七堵），
# 故索引鍵的 town 也需去尾綴；村里名表內已存「核心名」（長安，不含「里」），
# 故 child/parent/2012里 一律再套 normalize(去村里尾綴) 以免兩側不對齊。
# ============================================================================
def _core_vill(name, normalize):
    """去村里尾綴（里/村）後再正規化，使沿革表用字與底圖／得票鍵收斂一致。"""
    s = str(name).strip()
    if s.endswith("里") or s.endswith("村"):
        s = s[:-1]
    return normalize(s)


def _core_town(name, normalize):
    """去鄉鎮市區尾綴（區/鎮/鄉/市）後再正規化。"""
    s = str(name).strip()
    if s and s[-1] in "區鎮鄉市":
        s = s[:-1]
    return normalize(s)


