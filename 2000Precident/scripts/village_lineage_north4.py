# ===================== twvillage2012.json 村里名修補 =====================
# twvillage2012.json 把 Big5 無法表示的罕見字存成私用區(PUA)碼位，或以「■」(U+25A0) 代替。
# 下表把這些字還原成 2000 得票資料／官方所用正字（同 Converge_to_map1.py 的 VARIANT_CHAR_MAP 精神）。
JSON_PUA_TRANS = str.maketrans({
    "\ue6ff": "峰",   # 峯 → 峰：瑞芳爪[峯]、土城[峯]廷、新店五[峯]
    "\ue8d7": "腳",   # 脚 → 腳：萬里崁[腳]
    "\uee8e": "濂",   # 瑞芳[濂]新、[濂]洞
    "\ueebe": "館",   # 板橋公[館]、三峽永[館]
})

# 「■」為單一佔位符，可能代表不同罕見字，無法全域對應，故以「(縣市,鄉鎮,原名) → 正名」逐一指定；
# 正名依 2000 得票資料核對（見缺資料報告第 3 節「得票資料有、底圖卻無」）。
JSON_NAME_REPAIR = {
    ("新北市", "中和區", "瓦■里"): "瓦窯里",   # 瓦磘/瓦窯；2000 資料作「瓦窯」
    ("新北市", "中和區", "灰■里"): "灰窯里",   # 灰嗂/灰磘；2000 資料作「灰嗂」（嗂、磘皆窯之異體）
    ("新北市", "坪林區", "石■里"): "石槽里",   # 石曹/石槽；2000 資料作「石槽」
    ("新北市", "樹林區", "■寮里"): "羌寮里",   # 獇寮/羌寮；2000 資料作「羌寮」
    ("新北市", "永和區", "新■里"): "新部里",   # 新廍/新部；2000 資料作「新部」
    ("臺北市", "萬華區", "糖■里"): "糖部里",   # 糖廍/糖部；2000 資料作「糖部」
}

# 2000 資料側的異體字（與 PUA/■ 修補後的正名對齊；normalize 後再收斂一次）
VARIANT_CHAR_MAP_2000 = str.maketrans({
    "嗂": "窯",   # 中和灰[嗂] → 灰窯（與 JSON 灰■ 修補後同名）
})


def repair_json_vill_name(county, town, village):
    """把 twvillage2012.json 的村里名還原成正字。

    回傳 (修補後名稱, 是否修補, 說明)；說明為「原名 → 正名」以便記入報告。
    """
    if not isinstance(village, str) or village == "":
        return village, False, ""
    orig = village
    v = village.translate(JSON_PUA_TRANS)
    if (county, town, orig) in JSON_NAME_REPAIR:
        v = JSON_NAME_REPAIR[(county, town, orig)]
    if v != orig:
        return v, True, f"{orig} → {v}"
    return v, False, ""
