# 2004 → 2012 的鄉鎮市區／村里「更名」（非拆併，是同一單元改名）：
#   (縣市_core, 鄉鎮市區_core_2004, 村里_core_2004) → (鄉鎮市區_core_2012, 村里_core_2012)
#   鍵值皆為「去尾綴、正規化」後的 core（鄉鎮去 鄉/鎮/市/區，村里去 村/里）。
#   用途：得票資料讀入時先把 2004 名改寫為 2012 底圖名，之後即能精確匹配。
#   注意：**必須以 (縣市,鄉鎮,村里) 三元組為鍵**——不可只做鄉鎮名對照，
#         因 2004「高雄縣三民鄉」與 2012「高雄市三民區」同名會互相污染。
