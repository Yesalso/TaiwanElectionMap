# 2012 得票資料側的異體字 → 收斂（與 PUA/■ 修補後的正名對齊）
VARIANT_CHAR_MAP_2012 = str.maketrans({})

# 2012 得票資料側的破損／誤植村名修補：(縣市, 鄉鎮市區, 得票資料村里) → 正名
#   （正規化、去「村/里」尾綴後再查表）
VOTE_NAME_REPAIR = {
    # 來源 xlsx 該格字元毀損（石＋U+FFFD＋晪＋U+FFFD）；正字依 twvillage2012「石墻村」
    ("苗栗縣", "公館", "石\ufffd晪\ufffd"): "石墻",
    # 註：1996 版另有 ("新竹市","東","偉功") → "武功"（當時資料僅有「偉功里」，疑為「武功里」誤植）；
    #     2008 版資料「偉功里」與「武功里」並存，故當時亦不設此條。2012 資料的新竹市東區
    #     僅存「武功里」（無「偉功里」）→ 亦無需此條，直接精確匹配。
}


def repair_json_vill_name(county, town, village):
    """把 twvillage2012.json 的村里名還原成正字。

    回傳 (修補後名稱, 是否修補, 說明)；說明為「原名 → 正名」以便記入報告。
    """
    if not isinstance(village, str) or village == "":
        return village, False, ""
    orig = village
    v = village.translate(JSON_PUA_TRANS)
    if (county, town, orig) in JSON_NAME_REPAIR:
        v = JSON_NAME_REPAIR[(county, town, orig)]
    if v != orig:
        return v, True, f"{orig} → {v}"
    return v, False, ""
